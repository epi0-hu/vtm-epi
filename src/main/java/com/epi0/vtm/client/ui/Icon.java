package com.epi0.vtm.client.ui;

import net.minecraft.client.gui.GuiGraphics;

/** Small pixel icons (8 x 8), drawn with fills so they take any colour and need no textures. */
public enum Icon {
    DROP("...#....", "...#....", "..###...", "..###...", ".#####..", ".#####..", ".#####..", "..###..."),
    BOOK(".######.", ".#....#.", ".#.##.#.", ".#....#.", ".#.##.#.", ".#....#.", ".######.", "........"),
    BOLT("....##..", "...##...", "..##....", ".######.", "...##...", "..##....", ".##.....", "........"),
    STAR("...##...", "...##...", "########", ".######.", "..####..", "..#..#..", ".#....#.", "........"),
    BANNER("########", "#......#", "#......#", "#......#", "#......#", ".#....#.", "..#..#..", "...##..."),
    SKULL("..####..", ".######.", "##.##.##", "########", ".######.", "..#..#..", "..####..", "..#..#.."),
    CROWN("#..#..#.", "##.##.##", "########", "########", ".######.", ".######.", "........", "........"),
    MAP("###..###", "#.#..#.#", "#.####.#", "#..##..#", "#..##..#", "#.####.#", "#.#..#.#", "###..###"),
    SCROLL(".######.", "#......#", ".#####..", "..#.##..", "..#.#...", ".#####..", "#......#", ".######."),
    PEOPLE("..##..##", ".####.##", "..##..##", ".####.##", "#.##.#..", "#.##.#..", "..##....", "..##...."),
    FANGS("########", "#######.", ".#....#.", ".#....#.", ".#....#.", "..#..#..", "..#..#..", "...##..."),
    THRONE("#......#", "#.####.#", "#.#..#.#", "######.#", "#.#..#.#", "#.####.#", "#......#", "########"),
    EYE("........", "..####..", ".#.##.#.", "#.####.#", "#.####.#", ".#.##.#.", "..####..", "........"),
    COIN("..####..", ".#....#.", "#..##..#", "#.#..#.#", "#.#..#.#", "#..##..#", ".#....#.", "..####.."),
    WARN("...##...", "...##...", "..####..", "..####..", ".##..##.", ".##..##.", "########", "########"),
    CHECK("........", ".......#", "......##", "#....##.", "##..##..", ".####...", "..##....", "........");

    private final boolean[][] pixels = new boolean[8][8];

    Icon(String... rows) {
        for (int y = 0; y < 8; y++) {
            for (int x = 0; x < 8; x++) {
                pixels[y][x] = rows[y].charAt(x) == '#';
            }
        }
    }

    /** Draws the icon at {@code (x, y)}; {@code scale} 1 is 8 x 8 pixels. */
    public void draw(GuiGraphics g, int x, int y, int color, int scale) {
        for (int py = 0; py < 8; py++) {
            for (int px = 0; px < 8; px++) {
                if (pixels[py][px]) {
                    g.fill(x + px * scale, y + py * scale, x + (px + 1) * scale, y + (py + 1) * scale, color);
                }
            }
        }
    }
}
